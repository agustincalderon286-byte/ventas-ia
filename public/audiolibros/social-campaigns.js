export const SOCIAL_NETWORKS = Object.freeze(['facebook', 'instagram', 'youtube', 'tiktok']);
export const SOCIAL_ALIASES = Object.freeze({ fb: 'facebook', ig: 'instagram', msg: 'messenger', an: 'audience_network' });
export const SOCIAL_CAMPAIGN = 'tec_redes_es';
export const META_CAMPAIGN = 'tec_meta_es';
const piecesById = new Map(SOCIAL_PIECES.map(piece => [piece.id, piece]));
export function socialPiece(id) { return typeof id === 'string' ? piecesById.get(id) || null : null; }
export function normalizeSocialSource(source) { return Object.hasOwn(SOCIAL_ALIASES, source) ? SOCIAL_ALIASES[source] : source; }
export function socialCampaign(source, content = 'perfil') {
  source = normalizeSocialSource(source);
  const piece = socialPiece(content);
  if (piece?.format === 'ad') {
    if (!['meta', 'facebook', 'instagram', 'messenger', 'audience_network'].includes(source)) return {};
    return { campaign_source: source, campaign_medium: 'paid_social', campaign_name: META_CAMPAIGN, campaign_content: content };
  }
  if (!SOCIAL_NETWORKS.includes(source) || (!['perfil', 'origen_sin_reel'].includes(content) && (!piece || piece.source !== source))) return {};
  return { campaign_source: source, campaign_medium: 'social', campaign_name: SOCIAL_CAMPAIGN, campaign_content: content };
}
export function socialLink(source, content = 'perfil') {
  const campaign = socialCampaign(source, content);
  if (!campaign.campaign_name) return null;
  return '/audiolibros/r/' + campaign.campaign_source + '/' + content;
}
export function socialReferral(value) {
  try {
    const url = new URL(value); if (url.protocol !== 'https:') return {};
    const hosts = {
      'www.facebook.com': 'facebook', 'facebook.com': 'facebook', 'm.facebook.com': 'facebook', 'l.facebook.com': 'facebook', 'lm.facebook.com': 'facebook',
      'www.instagram.com': 'instagram', 'instagram.com': 'instagram', 'l.instagram.com': 'instagram',
      'www.youtube.com': 'youtube', 'youtube.com': 'youtube', 'm.youtube.com': 'youtube', 'youtu.be': 'youtube',
      'www.tiktok.com': 'tiktok', 'tiktok.com': 'tiktok', 'vm.tiktok.com': 'tiktok', 'vt.tiktok.com': 'tiktok'
    };
    return Object.hasOwn(hosts, url.hostname) ? socialCampaign(hosts[url.hostname], 'origen_sin_reel') : {};
  } catch { return {}; }
}
